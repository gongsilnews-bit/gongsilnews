      // 본문 상단에 대표 썸네일 이미지 포맷 삽입
      const finalContent = `<div style="text-align: center;"><img src="${item.thumbnailUrl}" style="max-width: 100%; height: auto; border-radius: 8px;" /></div><br/>${item.content}`;

