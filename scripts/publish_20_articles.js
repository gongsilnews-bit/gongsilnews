async function publishAllArticles() {
  console.log(`Starting publication of ${articlesData.length} premium articles for ${ADMIN_EMAIL}...`);

  const results = [];

  for (let i = 0; i < articlesData.length; i++) {
    const item = articlesData[i];
    console.log(`\n[${i + 1}/${articlesData.length}] Publishing: "${item.title}" (${item.section1} > ${item.section2})...`);

    // 본문 상단에 썸네일 이미지 div 삽입
    const finalContent = `<div style="text-align: center;"><img src="${item.thumbnailUrl}" style="max-width: 100%; height: auto; border-radius: 8px;" /></div><br/>${item.contentBody}`;

    // 타임스탬프를 1분 단위로 살짝 분산하여 자연스러운 타임라인 생성
    const publishedDate = new Date(Date.now() - (articlesData.length - 1 - i) * 60 * 1000).toISOString();

    try {
      // 1. articles 테이블에 INSERT (APPROVED 상태)
      const { data: article, error: articleError } = await supabase
        .from('articles')
        .insert({
          title: item.title,
          subtitle: item.subtitle,
          content: finalContent,
          section1: item.section1,
          section2: item.section2,
          status: 'APPROVED',
          published_at: publishedDate,
          thumbnail_url: item.thumbnailUrl,
          youtube_url: null,
          is_headline: item.isHeadline,
          is_important: item.isImportant,
          author_id: ADMIN_ID,
          author_name: ADMIN_NAME,
          author_email: ADMIN_EMAIL,
        })
        .select('id')
        .single();

      if (articleError) {
        console.error(`  -> Error inserting article:`, articleError.message);
        results.push({ idx: i + 1, title: item.title, status: 'error', error: articleError.message });
        continue;
      }

      console.log(`  -> Article created with ID: ${article.id}`);

      // 2. article_media 테이블에 등록 (관리자 수정화면 및 미디어 관리 완벽 연동)
      const { error: mediaError } = await supabase
        .from('article_media')
        .insert({
          article_id: article.id,
          media_type: 'PHOTO',
          url: item.thumbnailUrl,
          sort_order: 0
        });

      if (mediaError) {
        console.warn(`  -> Warning inserting media:`, mediaError.message);
      } else {
        console.log(`  -> Media record linked.`);
      }

      // 3. article_keywords 테이블에 등록
      if (item.keywords && item.keywords.length > 0) {
        const keywordRows = item.keywords.map(kw => ({
          article_id: article.id,
          keyword: kw.trim()
        }));

        const { error: kwError } = await supabase
          .from('article_keywords')
          .insert(keywordRows);

        if (kwError) {
          console.warn(`  -> Warning inserting keywords:`, kwError.message);
        } else {
          console.log(`  -> ${item.keywords.length} keywords attached.`);
        }
      }

      results.push({ idx: i + 1, id: article.id, title: item.title, status: 'success' });
    } catch (err) {
      console.error(`  -> Unexpected error:`, err.message);
      results.push({ idx: i + 1, title: item.title, status: 'error', error: err.message });
    }
  }

  console.log("\n=================================");
  console.log(`Publication finished! Success: ${results.filter(r => r.status === 'success').length}/${articlesData.length}`);
  console.log("=================================");
}

publishAllArticles();
