/* ── 매물 정보를 프롬프트에 넣을 줄로 만든다 ──
   상세 표는 매물 종류마다 항목이 다르다. 그래서 정해진 목록을 쓰지 않고
   화면에서 읽어온 것을 순서 그대로 전부 넘긴다.
   값이 없는 항목은 아예 쓰지 않는다 — AI 가 빈칸을 상상하지 않도록. */
function gwFactLines(v) {
  const lines = [];
  const seen = new Set();

  const push = (label, value) => {
    const val = value == null ? "" : String(value).trim();
    if (!label || !val || val === "-" || seen.has(label)) return;
    seen.add(label);
    lines.push(`- ${label}: ${val}`);
  };

  push("매물", v.title);
  push("금액", v.priceText);
  for (const f of v.fields || []) push(f.label, f.value);
  push("특징", Array.isArray(v.themes) ? v.themes.join(" ") : v.themes);
  push("주변환경", v.infra);

  return lines.join("\n");
}

/* 표에서 라벨로 값 하나 꺼내기 */
function gwField(v, ...labels) {
  for (const want of labels) {
    const hit = (v.fields || []).find((f) => f.label === want);
    if (hit) return hit.value;
  }
  return "";
}

/* 기사 본문에 넣을 매물 표기 이름 */
function gwSubjectName(v) {
  return (
    (v.title && v.title.trim()) ||
    gwField(v, "단지명", "건물명", "소재지") ||
    "해당 매물"
  );
}

