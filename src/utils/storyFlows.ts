export const storiesFor = (kind: "market" | "vacancy") => (kind === "market" ? MARKET_STORIES : VACANCY_STORIES);

/** 블로그·SNS·쇼츠·기사에 붙이는 한 덩어리 — 모든 글이 같은 이야기·같은 순서로 이어지게 */
export function storyBlock(kind: "market" | "vacancy", id: string | undefined, medium: "article" | "blog" | "sns" | "shorts"): string {
  const s = storiesFor(kind).find((x) => x.id === id);
  if (!s) return "";
  const lead = medium === "article"
    ? `첫 문단과 제목은 ${s.title}.`
    : `첫 말은 ${s.hook}.`;
  return `

[이야기 — 위 지시보다 먼저: 기사·블로그·SNS·쇼츠가 모두 '${s.name}' 이야기로 이어집니다]
- 이 글은 '${s.name}'(${s.desc}) 이야기입니다. ${lead}
- 순서: ${s.flow}. 이 순서대로 앞 문장·문단에 물 흐르듯 이어 쓰고, 중간에 다른 이야기로 튀지 마십시오.
- 이 이야기에 필요한 사실만 고르고, 나머지 숫자는 쓰지 않습니다.`;
}
